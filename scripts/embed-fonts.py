#!/usr/bin/env python3
"""
Embeds subsetted brand fonts into the README's SVG banners.

Why: GitHub renders every SVG here through an <img>, and an SVG image may not
fetch anything, so `font-family: 'Space Grotesk', ...` only works for the rare
visitor who has the font installed. Everyone else gets Segoe UI, Helvetica or
Georgia, and the wordmark stops looking like aniksarkerakash.com. A data: URI
is not a fetch, so an @font-face carrying the font inline renders everywhere,
and if a renderer refuses it the existing fallback stack still applies.

Each font is cut down to the characters the file actually draws, so the cost
is a few KB per face rather than the whole family. That also means:

    EDIT THE COPY IN AN SVG -> RE-RUN THIS SCRIPT ON IT.

A glyph missing from the subset falls through to the fallback font for that
one character, which reads as a typo.

    pip install fonttools brotli
    python3 scripts/embed-fonts.py assets/hero.svg assets/footer.svg

Idempotent: the generated block sits between the two marker comments below
and is replaced on every run. All three faces are SIL Open Font License 1.1.
"""

import base64
import io
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET

from fontTools import subset
from fontTools.ttLib import TTFont

START = '/* @font-face:start (generated by scripts/embed-fonts.py) */'
END = '/* @font-face:end */'

UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36'

# family -> (Google Fonts css2 query, @font-face descriptors, CSS class that selects it)
FACES = {
    'Space Grotesk': ('Space+Grotesk:wght@300..700', 'font-weight: 300 700;', 'fs'),
    'JetBrains Mono': ('JetBrains+Mono:wght@400..800', 'font-weight: 400 800;', 'fm'),
    'Instrument Serif': ('Instrument+Serif:ital@1', 'font-style: italic;', 'fe'),
}

SVG_NS = '{http://www.w3.org/2000/svg}'


def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=30) as res:
        return res.read()


def latin_woff2(query):
    """The basic-Latin woff2 Google Fonts serves for a css2 query."""
    css = fetch(f'https://fonts.googleapis.com/css2?family={query}&display=swap').decode()
    for block in css.split('@font-face')[1:]:
        if 'U+0000-00FF' in block:
            return fetch(re.search(r'url\((https://[^)]+\.woff2)\)', block).group(1))
    raise SystemExit(f'no latin subset for {query}')


def text_by_class(svg_path):
    """Characters drawn per font class, following class inheritance down <g>/<text>/<tspan>."""
    chars = {cls: set() for _, _, cls in FACES.values()}

    def walk(el, inherited):
        classes = inherited | set((el.get('class') or '').split())
        if el.tag in (SVG_NS + 'text', SVG_NS + 'tspan'):
            for cls in chars:
                if cls in classes:
                    chars[cls].update(el.text or '')
        for child in el:
            walk(child, classes)
            # Tail text belongs to the parent's font, not the child's.
            if el.tag in (SVG_NS + 'text', SVG_NS + 'tspan'):
                for cls in chars:
                    if cls in classes:
                        chars[cls].update(child.tail or '')

    walk(ET.parse(svg_path).getroot(), set())
    return chars


def subset_woff2(raw, chars):
    # recalcTimestamp off: otherwise head.modified changes on every run and the
    # SVG diffs even when no glyph did.
    font = TTFont(io.BytesIO(raw), recalcTimestamp=False)
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['kern', 'liga', 'calt']  # keep spacing, drop everything decorative
    opts.name_IDs = [0, 1, 2, 13, 14]                # keep the copyright and OFL notice
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(text=''.join(sorted(chars | {' '})))
    sub.subset(font)
    out = io.BytesIO()
    font.flavor = 'woff2'
    font.save(out)
    return out.getvalue()


def main(paths):
    cache = {}
    for path in paths:
        src = open(path, encoding='utf-8').read()
        chars = text_by_class(path)
        rules = []
        for family, (query, descriptors, cls) in FACES.items():
            used = {c for c in chars[cls] if not c.isspace()}
            if not used:
                continue
            if query not in cache:
                cache[query] = latin_woff2(query)
            data = subset_woff2(cache[query], used)
            b64 = base64.b64encode(data).decode()
            rules.append(f"      @font-face {{ font-family: '{family}'; {descriptors} "
                         f"src: url(data:font/woff2;base64,{b64}) format('woff2'); }}")
            print(f'{path}: {family:16s} {len(used):3d} glyphs  {len(data):6d} B')
        block = f'{START}\n' + '\n'.join(rules) + f'\n      {END}'

        if START in src:
            src = re.sub(re.escape(START) + r'.*?' + re.escape(END), lambda _: block, src, flags=re.S)
        else:
            # First run: open the first <style> with the block.
            src = re.sub(r'<style>\n?', lambda _: f'<style>\n      {block}\n', src, count=1)
        open(path, 'w', encoding='utf-8', newline='\n').write(src)


if __name__ == '__main__':
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    main(sys.argv[1:])
